using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace RuntimeFlow.Generators
{
    /// <summary>
    /// Emits, for every assembly that references RuntimeFlow, the list of its types the runtime discovery looks at:
    /// types implementing IAsyncInitializableService and interfaces that extend other interfaces. The runtime reads
    /// the catalog instead of reflecting over every type of the assembly: under IL2CPP reflection over a type
    /// initializes its class, and that metadata is never freed.
    /// The lists are supersets of metadata names (Outer`1+Inner), which the runtime resolves with Assembly.GetType:
    /// a name reaches private nested types too, and resolving it initializes nothing else.
    /// </summary>
    [Generator(LanguageNames.CSharp)]
    public sealed class TypeCatalogGenerator : IIncrementalGenerator
    {
        public const string CatalogNamespace = "RuntimeFlow.Contexts.Generated";
        public const string CatalogTypeName = "RuntimeFlowTypeCatalog";
        private const string AsyncInitInterface = "RuntimeFlow.Contexts.IAsyncInitializableService";
        private const string PreserveAttribute = "UnityEngine.Scripting.PreserveAttribute";

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterSourceOutput(context.CompilationProvider, static (spc, compilation) =>
            {
                var source = Render(compilation);
                if (source != null)
                    spc.AddSource(CatalogTypeName + ".g.cs", SourceText.From(source, Encoding.UTF8));
            });
        }

        private static string? Render(Compilation compilation)
        {
            var contract = compilation.GetTypeByMetadataName(AsyncInitInterface);
            if (contract == null)
                return null;

            var asyncTypes = new List<string>();
            var derivedInterfaces = new List<string>();
            foreach (var type in EnumerateNamedTypes(compilation.Assembly.GlobalNamespace))
            {
                if (SymbolEqualityComparer.Default.Equals(type, contract)
                    || type.AllInterfaces.Contains(contract, SymbolEqualityComparer.Default))
                    asyncTypes.Add(MetadataName(type));
                if (type.TypeKind == TypeKind.Interface && type.AllInterfaces.Length > 0)
                    derivedInterfaces.Add(MetadataName(type));
            }

            var preserve = compilation.GetTypeByMetadataName(PreserveAttribute) != null
                ? "    [global::" + PreserveAttribute + "]\n"
                : string.Empty;
            var builder = new StringBuilder();
            builder.Append("// <auto-generated/>\n");
            builder.Append("namespace ").Append(CatalogNamespace).Append("\n{\n");
            builder.Append(preserve);
            builder.Append("    internal static class ").Append(CatalogTypeName).Append("\n    {\n");
            AppendNames(builder, "AsyncInitializableTypes", asyncTypes);
            AppendNames(builder, "DerivedInterfaces", derivedInterfaces);
            builder.Append("    }\n}\n");
            return builder.ToString();
        }

        private static void AppendNames(StringBuilder builder, string field, List<string> names)
        {
            names.Sort(System.StringComparer.Ordinal);
            builder.Append("        public static readonly string[] ").Append(field).Append(" =\n        {\n");
            foreach (var name in names)
                builder.Append("            \"").Append(name).Append("\",\n");
            builder.Append("        };\n");
        }

        // The name Assembly.GetType resolves: Namespace.Outer`1+Inner`2
        private static string MetadataName(INamedTypeSymbol type)
        {
            if (type.ContainingType != null)
                return MetadataName(type.ContainingType) + "+" + type.MetadataName;
            return type.ContainingNamespace.IsGlobalNamespace
                ? type.MetadataName
                : type.ContainingNamespace.ToDisplayString() + "." + type.MetadataName;
        }

        private static IEnumerable<INamedTypeSymbol> EnumerateNamedTypes(INamespaceSymbol root)
        {
            foreach (var member in root.GetMembers())
            {
                if (member is INamespaceSymbol nested)
                {
                    foreach (var type in EnumerateNamedTypes(nested))
                        yield return type;
                }
                else if (member is INamedTypeSymbol type)
                {
                    foreach (var named in WithNested(type))
                        yield return named;
                }
            }
        }

        private static IEnumerable<INamedTypeSymbol> WithNested(INamedTypeSymbol type)
        {
            yield return type;
            foreach (var nested in type.GetTypeMembers())
            {
                foreach (var named in WithNested(nested))
                    yield return named;
            }
        }
    }
}
